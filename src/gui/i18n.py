    base = STRINGS.get(lang, STRINGS[LANG_EN])
    value = base.get(key, STRINGS[LANG_EN].get(key, key))
    if kwargs:
        try:
            return value.format(**kwargs)
        except (KeyError, ValueError):
            return value
    return value
